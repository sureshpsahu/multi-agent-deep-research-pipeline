"""
Multi-Agent Deep Research & Telemetry Pipeline (Project 2).

This script orchestrates a three-stage research workflow using Claude and Python:
1. Planner Agent: Decomposes a complex business topic into focused sub-queries.
2. Parallel Search/Browse Workers: Execute concurrent web lookups and strip raw HTML
   down to high-signal passages to reduce context-window token costs.
3. Synthesizer Agent: Compiles all passages into an executive brief with citations
   while `telemetry.py` tracks P95 latency, HTTP 429 retries, and token savings.
"""

import os
import json
import argparse
from concurrent.futures import ThreadPoolExecutor
import requests
from dotenv import load_dotenv
from anthropic import Anthropic
from telemetry import DevExTelemetryTracker

# Load environment configuration from local .env file
load_dotenv()

ANTHROPIC_API_KEY = os.getenv("ANTHROPIC_API_KEY")
SEARCH_API_KEY = os.getenv("SEARCH_API_KEY")
MAX_WORKERS = int(os.getenv("MAX_PARALLEL_WORKERS", "3"))
PASSAGE_MODE = os.getenv("PASSAGE_EXTRACTION_MODE", "true").lower() == "true"

# Initialize Anthropic client and shared telemetry tracker
client = Anthropic(api_key=ANTHROPIC_API_KEY)
tracker = DevExTelemetryTracker()


def planner_agent(topic):
    """
    Agent 1 (Planner): Breaks a broad research topic into 3 focused web sub-queries.

    Args:
        topic (str): The high-level business or technical research question.

    Returns:
        list[str]: A list of 3 targeted search queries.
    """
    # Fallback sub-queries when running locally without an Anthropic API key
    if not ANTHROPIC_API_KEY or ANTHROPIC_API_KEY == "your_claude_key":
        return [
            f"{topic} market trends",
            f"{topic} developer onboarding challenges",
            f"{topic} enterprise pricing and metering",
        ]

    prompt = (
        f"Break this research topic into exactly 3 focused web search queries. "
        f"Return ONLY a JSON list of 3 strings, nothing else.\nTopic: {topic}"
    )
    resp = client.messages.create(
        model="claude-3-5-sonnet-latest",
        max_tokens=200,
        messages=[{"role": "user", "content": prompt}],
    )
    try:
        queries = json.loads(resp.content[0].text)
        return queries[:3]
    except Exception:
        # Fallback if the model returns non-JSON text
        return [f"{topic} overview", f"{topic} architecture", f"{topic} benchmarks"]


def search_and_extract_worker(sub_query):
    """
    Agent 2 (Parallel Worker): Searches the web for a single sub-query and applies
    passage-extraction filtering to trim bloated raw HTML down to concise snippets.

    Args:
        sub_query (str): A focused sub-query generated by the Planner Agent.

    Returns:
        dict: Contains 'passages' (list of dicts), 'raw_chars' (int), and
              'extracted_chars' (int) to measure token reduction.
    """
    if SEARCH_API_KEY and SEARCH_API_KEY != "your_search_key":
        url = "https://tavily.com"
        payload = {
            "api_key": SEARCH_API_KEY,
            "query": sub_query,
            "search_depth": "advanced",
            "include_raw_content": True,
            "max_results": 2,
        }
        resp = requests.post(url, json=payload, timeout=20)
        resp.raise_for_status()
        data = resp.json()

        passages = []
        raw_chars = 0
        extracted_chars = 0

        for item in data.get("results", []):
            # Measure full raw page size vs. filtered passage size
            full_page = item.get("raw_content") or item.get("content", "")
            raw_chars += len(full_page)

            if PASSAGE_MODE:
                # Keep only the high-signal 500-char snippet to save input tokens
                selected_text = item.get("content", "")[:500]
            else:
                # Raw ingestion mode sends larger chunks into the context window
                selected_text = full_page[:2500]

            extracted_chars += len(selected_text)
            passages.append({
                "sub_query": sub_query,
                "title": item.get("title", ""),
                "url": item.get("url", ""),
                "passage": selected_text,
            })

        return {
            "passages": passages,
            "raw_chars": raw_chars,
            "extracted_chars": extracted_chars,
        }

    # Simulated worker output so the pipeline runs end-to-end without paid keys
    simulated_passage = (
        f"Key industry findings for '{sub_query}': standardized APIs and passage "
        f"filtering reduce LLM token costs by over 40%."
    )
    return {
        "passages": [{
            "sub_query": sub_query,
            "title": f"Report: {sub_query}",
            "url": "https://example.com",
            "passage": simulated_passage,
        }],
        "raw_chars": 2400,
        "extracted_chars": len(simulated_passage),
    }


def synthesizer_agent(topic, all_passages):
    """
    Agent 3 (Synthesizer): Compiles all worker passages into an executive brief
    with inline source titles and URLs.

    Args:
        topic (str): The original research topic.
        all_passages (list[dict]): Combined list of extracted passages from all workers.

    Returns:
        str | Message: Markdown string (demo mode) or Anthropic Message object.
    """
    if not ANTHROPIC_API_KEY or ANTHROPIC_API_KEY == "your_claude_key":
        lines = [f"# Executive Research Brief: {topic}\n", "## Key Findings"]
        for p in all_passages:
            lines.append(f"- **{p['title']}**: {p['passage']} ([Source]({p['url']}))")
        return "\n".join(lines)

    prompt = (
        f"Write a concise executive research brief on '{topic}' using ONLY the passages below. "
        f"Include inline source titles and URLs for every claim.\n\n"
        f"Passages:\n{json.dumps(all_passages, indent=2)}"
    )
    resp = client.messages.create(
        model="claude-3-5-sonnet-latest",
        max_tokens=1000,
        messages=[{"role": "user", "content": prompt}],
    )
    return resp


def main():
    """
    Main entry point: runs the Planner -> Parallel Workers -> Synthesizer pipeline,
    tracks rate-limit retries and token savings, and exports `telemetry_scorecard.json`.
    """
    parser = argparse.ArgumentParser(description="Multi-Agent Deep Research Pipeline")
    parser.add_argument(
        "--topic",
        type=str,
        default="Enterprise AI grounding adoption and API monetization models",
        help="Research topic for the multi-agent pipeline",
    )
    args = parser.parse_args()

    print(f"\nStarting Deep Research Pipeline on: '{args.topic}'")
    print(f"Parallel workers: {MAX_WORKERS} | Passage extraction mode: {PASSAGE_MODE}\n")

    # Step 1: Planner Agent decomposes the topic into sub-queries
    sub_queries = tracker.execute_with_telemetry(
        step_name="planner_agent",
        fn=planner_agent,
        topic=args.topic,
    )
    if not isinstance(sub_queries, list):
        sub_queries = [f"{args.topic} overview", f"{args.topic} architecture", f"{args.topic} metering"]

    print(f"Planned sub-queries: {sub_queries}\n")

    # Step 2: Execute Search/Browse Workers concurrently using a thread pool
    def run_worker(q):
        """Helper wrapper to run each worker call through the telemetry tracker."""
        return tracker.execute_with_telemetry(
            step_name="parallel_search_worker",
            fn=search_and_extract_worker,
            sub_query=q,
        )

    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        worker_outputs = list(executor.map(run_worker, sub_queries))

    # Flatten all extracted passages into a single list for synthesis
    all_passages = []
    for out in worker_outputs:
        all_passages.extend(out["passages"])

    # Step 3: Synthesizer Agent compiles the final executive brief
    synthesis_result = tracker.execute_with_telemetry(
        step_name="synthesizer_agent",
        fn=synthesizer_agent,
        topic=args.topic,
        all_passages=all_passages,
    )

    if isinstance(synthesis_result, str):
        report_text = synthesis_result
    else:
        report_text = synthesis_result.content[0].text

    print("=== Final Synthesized Brief ===\n")
    print(report_text)

    # Step 4: Print and export the DevEx telemetry scorecard
    scorecard = tracker.generate_scorecard()
    print("\n=== Pipeline Telemetry Scorecard ===")
    print(json.dumps(scorecard, indent=2))

    tracker.export_report("telemetry_scorecard.json")
    print("\nSaved detailed trace to telemetry_scorecard.json")


if __name__ == "__main__":
    main()
